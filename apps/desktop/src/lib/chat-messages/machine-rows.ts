/**
 * Machine rows typed at read time, so history stored by an older backend renders by the same rules
 * as rows the current backend types at write time (no database rewrite).
 *
 * A `user` row is the person only when the person wrote it. Rows the runtime wrote into the user
 * role (a scheduled job's output, a bot's task brief, a background-process completion, a runtime
 * notification) become typed notices here and paint as one quiet event row each, never as the
 * user's own bubble. An interrupt sentinel stored as assistant prose paints nothing. A
 * `[IMPORTANT: Background process ...]` row stays a user row, typed or not (a person may quote the
 * marker, #112144); the thread renders it as a process note titled by `processNotificationTitle`.
 *
 * Retyping needs machine provenance: a row is a machine event only on a positive machine signature.
 * Anything else keeps its stored role and kind, so a person's words (a voice line the gateway typed
 * `internal_notification`, a pasted cron frame) stay the person's bubble. The Python twin is
 * agent/display_row_typing.py; tests/fixtures/cron_frame_cases.json and
 * tests/fixtures/interrupt_sentinel_cases.json pin both.
 */
import { relabelProcessTitle } from '@/lib/process-title'
import type { SessionMessage } from '@/types/hermes'

/** Desktop display kinds for runtime-written user rows (the backend serves the first two too). */
export const CRON_DELIVERY_KIND = 'cron_delivery'
export const BOT_BRIEF_KIND = 'bot_brief'
export const RUNTIME_NOTICE_KIND = 'runtime_notice'

export type MachineEventKind = 'brief' | 'cron' | 'notice' | 'process'

export const MACHINE_EVENT_KINDS: Readonly<Record<string, MachineEventKind>> = {
  [BOT_BRIEF_KIND]: 'brief',
  [CRON_DELIVERY_KIND]: 'cron',
  [RUNTIME_NOTICE_KIND]: 'notice'
}

// cron/scheduler_delivery.py::bot_chat_message: `[Cronjob "<name>" output \u2014 ...]\n\n<output>`.
// Lenient (older wordings): parses a row that already carries machine provenance, never decides it.
const CRON_FRAME_RE = /^\[Cronjob "(.*?)" output\b[^\]]*\]\s*/
// The exact frame the writer stamps, the only proof an UNTYPED legacy row is a cron delivery.
const CRON_WRITER_FRAME_RE = /^\[Cronjob "(.*?)" output \u2014 scheduled job, not the user\./

// The runtime's information-free interrupt sentinels (INTERRUPT_WAITING_FOR_MODEL_PREFIX and the
// retry/recovery `interrupt_text`s in agent/turn_*.py), which a backend before the fix stored as
// the turn's assistant prose. Any other "Operation interrupted" text is prose and stays visible.
const INTERRUPT_SENTINEL_RE =
  /^Operation interrupted: (?:waiting for model response \(\d+(?:\.\d+)?s elapsed\)|waiting for the provider to recover \(cycle \d+\/\d+\)|retrying API call after error \(retry \d+\/\d+\)|retrying empty response from model \(retry \d+\/\d+\))\.$/

// The background-process frame user-message.tsx renders as a process note (content.ts
// PROCESS_NOTIFICATION_RE); such a row keeps its stored kind.
const PROCESS_NOTIFICATION_RE = /^\[IMPORTANT: Background process [\s\S]*\]$/
// Runtime frames a person never writes: a row typed `internal_notification` that opens with one of
// these, or carries the gateway footer (gateway/run_notifications.py INTERNAL_NOTIFICATION_FOOTER),
// is the runtime speaking.
const RUNTIME_FRAME_RE = /^\[(?:IMPORTANT:|ASYNC DELEGATION|kanban\]|System note:|CONTEXT COMPACTION)/
const GATEWAY_FOOTER = '[INTERNAL NOTIFICATION \u2014 generated by the Hermes gateway'

// API-only turn notes an older gateway stored inside the person's own row (fixed at write time in
// gateway/run_turn_runner.py: the stored row holds the person's words only). Read-time heal so those
// rows show the question, not the note: the interrupted-turn recovery note and the model-switch note
// lead the text; the surface-switch note (and the guidance that may follow it) closes it.
const LEADING_TURN_NOTE_RE =
  /^\s*\[(?:System note: A new message has arrived\. The conversation history contains pending tool outputs from an interrupted turn\.|Note: model was just switched from )[^\]]*\]\s*/

const SURFACE_SWITCH_NOTE_RE = /\n\s*\[System: This conversation is now being answered on a different interface: [\s\S]*$/

/** The person's words of a stored user row, without API-only turn notes; the same string when none. */
export function stripApiOnlyTurnNotes(text: string): string {
  let words = text
  let lead: null | RegExpExecArray

  while ((lead = LEADING_TURN_NOTE_RE.exec(words)) && lead[0].length < words.length) {
    words = words.slice(lead[0].length)
  }

  const tail = SURFACE_SWITCH_NOTE_RE.exec(words)

  if (tail && tail.index > 0) {
    words = words.slice(0, tail.index)
  }

  return words === text ? text : words.trim()
}

function withoutApiOnlyTurnNotes(message: SessionMessage): SessionMessage {
  const field = typeof message.content === 'string' && message.content ? 'content' : 'text'
  const text = message[field]

  if (typeof text !== 'string' || !text) {
    return message
  }

  const words = stripApiOnlyTurnNotes(text)

  return words === text ? message : { ...message, [field]: words }
}

/** Whether the whole trimmed text is one of the runtime's information-free interrupt sentinels. */
export const isInterruptSentinel = (text: string) => INTERRUPT_SENTINEL_RE.test(text.trim())

type Metadata = Record<string, unknown>

function metadataOf(message: SessionMessage): Metadata {
  let parsed: unknown = message.display_metadata

  if (typeof parsed === 'string') {
    try {
      parsed = JSON.parse(parsed)
    } catch {
      return {}
    }
  }

  return parsed && typeof parsed === 'object' ? (parsed as Metadata) : {}
}

// The resume projection serves a row's words as `text`, the REST page as `content`.
const storedText = (message: SessionMessage) =>
  typeof message.content === 'string' && message.content
    ? message.content
    : typeof message.text === 'string'
      ? message.text
      : ''

function cronRow(message: SessionMessage, metadata: Metadata): null | SessionMessage {
  const text = storedText(message)
  const typed = metadata.cron_delivery && typeof metadata.cron_delivery === 'object' ? metadata.cron_delivery : null
  const kind = message.display_kind
  // Machine provenance first: a typed row may use any frame wording; an untyped legacy row only the
  // exact writer frame. A person pasting or quoting a frame keeps their own bubble.
  const provenance = Boolean(typed) || kind === 'internal_notification' || kind === CRON_DELIVERY_KIND
  const frame = provenance || CRON_WRITER_FRAME_RE.test(text) ? CRON_FRAME_RE.exec(text) : null

  if (!frame && !typed) {
    return null
  }

  const named = typed ? (typed as Metadata).job_name : undefined
  const jobName = (typeof named === 'string' && named.trim()) || frame?.[1]?.trim() || 'Scheduled job'
  const output = message.display_content ?? (frame ? text.slice(frame[0].length) : text)

  return {
    ...message,
    display_content: output,
    display_kind: CRON_DELIVERY_KIND,
    display_metadata: { ...metadata, display_text: jobName }
  }
}

function isRuntimeFrame(text: string): boolean {
  const trimmed = text.trim()

  if (PROCESS_NOTIFICATION_RE.test(trimmed)) {
    return false
  }

  return RUNTIME_FRAME_RE.test(trimmed) || trimmed.includes(GATEWAY_FOOTER)
}

function userMachineRow(stored: SessionMessage): SessionMessage {
  // A leading runtime note is split from the person's text first, so a row that opens with one is
  // still the person's bubble (and is retyped below only on a machine signature of what remains).
  const message = withoutApiOnlyTurnNotes(stored)
  const kind = message.display_kind
  const metadata = metadataOf(message)

  if (!kind || kind === 'internal_notification' || kind === CRON_DELIVERY_KIND) {
    const cron = cronRow(message, metadata)

    if (cron) {
      return cron
    }
  }

  if (!kind) {
    return message
  }

  if (kind === 'process_complete' && typeof metadata.display_text === 'string') {
    return { ...message, display_metadata: { ...metadata, display_text: relabelProcessTitle(metadata.display_text) } }
  }

  // A runtime notification is retyped only on a positive machine signature. Everything else typed
  // `internal_notification` (a voice line, an inter-agent delivery) keeps its stored kind.
  if (kind === 'internal_notification' && isRuntimeFrame(storedText(message))) {
    return { ...message, display_kind: RUNTIME_NOTICE_KIND }
  }

  return message
}

/** The row as the thread should read it. Returns the same object when nothing changes. */
export function typeMachineRow(message: SessionMessage): SessionMessage {
  if (message.role === 'user') {
    return userMachineRow(message)
  }

  if (message.role === 'assistant' && isInterruptSentinel(storedText(message))) {
    return { ...message, content: '', display_content: '' }
  }

  return message
}

/** The one-line label of a typed machine event row. */
export function machineEventLabel(kind: MachineEventKind, metadata: Metadata): string {
  if (kind === 'cron') {
    return typeof metadata.display_text === 'string' && metadata.display_text ? metadata.display_text : 'Scheduled job'
  }

  if (kind === 'brief') {
    const author = metadata.author && typeof metadata.author === 'object' ? (metadata.author as Metadata) : {}
    const raw = typeof author.name === 'string' && author.name.trim() ? author.name : author.id
    const name = typeof raw === 'string' ? raw.replace(/^bot:/, '').split(/\s+[|\u00b7\u2022\u2014\u2013]\s+/)[0] : ''

    return name ? `Brief from ${name}` : 'Task brief'
  }

  return 'Notification'
}

