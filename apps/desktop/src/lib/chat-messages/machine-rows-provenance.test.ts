// Machine-row typing needs machine provenance (polish fix 1119). A row is retyped as a machine
// event only on a positive machine signature; a person's words keep their own bubble. The cron
// and interrupt-sentinel cases are shared with the Python twin (agent/display_row_typing.py).
import { describe, expect, it } from 'vitest'

import type { SessionMessage } from '@/types/hermes'

import cronCases from '../../../../../tests/fixtures/cron_frame_cases.json'
import sentinelCases from '../../../../../tests/fixtures/interrupt_sentinel_cases.json'

import { CRON_DELIVERY_KIND, RUNTIME_NOTICE_KIND, typeMachineRow } from './machine-rows'
import { chatMessageText } from './parts'

import { toChatMessages } from '.'

const userRow = (content: string, display_kind?: null | string): SessionMessage =>
  ({ role: 'user', content, timestamp: 1, ...(display_kind ? { display_kind } : {}) }) as SessionMessage

describe('cron deliveries need machine provenance (shared cases)', () => {
  it.each(cronCases.cases)('$name', testCase => {
    const typed = typeMachineRow(userRow(testCase.text, testCase.display_kind))

    if (testCase.cron) {
      expect(typed.display_kind).toBe(CRON_DELIVERY_KIND)
      expect((typed.display_metadata as Record<string, unknown>).display_text).toBe(testCase.job_name)
      expect(typed.display_content).toBe(testCase.output)
    } else {
      expect(typed.display_kind ?? null).toBe(testCase.display_kind)
      expect(typed.content).toBe(testCase.text)
      expect(typed.display_content).toBeUndefined()
    }
  })

  it('types a row the backend marked with cron_delivery metadata, whatever its text', () => {
    const typed = typeMachineRow({
      ...userRow('Synced 4 channels.'),
      display_metadata: { cron_delivery: { job_name: 'slack-sync' } }
    } as SessionMessage)

    expect(typed.display_kind).toBe(CRON_DELIVERY_KIND)
    expect((typed.display_metadata as Record<string, unknown>).display_text).toBe('slack-sync')
  })

  it('keeps a pasted frame when the bot then chooses silence (hydration)', () => {
    const content = '[Cronjob "Team report" output - scheduled job]\n\nSave this report for tomorrow.'

    const rows = toChatMessages([
      { role: 'user', content, timestamp: 1 },
      { role: 'assistant', content: 'NO_REPLY', timestamp: 2 }
    ] as SessionMessage[])

    expect(rows.some(row => row.role === 'user' && chatMessageText(row) === content)).toBe(true)
  })
})

describe('interrupt sentinels (shared cases)', () => {
  it.each(sentinelCases.cases)('$text', ({ sentinel, text }) => {
    const typed = typeMachineRow({ role: 'assistant', content: text, timestamp: 1 } as SessionMessage)

    expect(typed.content).toBe(sentinel ? '' : text)
  })
})

describe('internal notifications are retyped only on a machine signature', () => {
  const kind = 'internal_notification'

  it.each([
    "Hey, what's on my calendar tomorrow morning?",
    'Give me a detailed rundown of everything on my calendar this week.',
    'Thanks, bye.',
    'Actually never mind, just book it.',
    'Message from Neo (@hermes): the deck is ready'
  ])('a person speaking keeps their row: %s', text => {
    const row = userRow(text, kind)

    expect(typeMachineRow(row)).toBe(row)
  })

  it('a background-process completion keeps its process-note path', () => {
    const row = userRow(
      '[IMPORTANT: Background process proc_151f1eb6add3 completed normally (exit code 0).\nCommand: W=/home/hermes/.hermes/work/asim-short-1119; ls]',
      kind
    )

    expect(typeMachineRow(row)).toBe(row)
  })

  it.each([
    '[IMPORTANT: 2 background processes completed.]',
    '[ASYNC DELEGATION BATCH COMPLETE] 3 tasks finished.',
    '[kanban] Task t_123 moved to done.',
    '[System note: The previous turn was interrupted.]',
    '[CONTEXT COMPACTION \u2014 earlier turns were summarized]',
    'The calendar sync finished.\n\n[INTERNAL NOTIFICATION \u2014 generated by the Hermes gateway, not the user.]'
  ])('a runtime frame becomes a runtime notice: %s', text => {
    expect(typeMachineRow(userRow(text, kind)).display_kind).toBe(RUNTIME_NOTICE_KIND)
  })
})
